/**
 * Access translation with fallback support
 * @param {string} lang - 'uz' | 'ru' | 'en'
 * @param {string} section - top-level section
 * @param {string} key - key within that section
 * @returns {string}
 */
export function getTranslation(lang = 'uz', section, key) {
  const selectedLang = translations[lang] || translations.uz;
  const selectedSection = selectedLang[section] || translations.uz[section] || {};
  return selectedSection[key] || translations.uz[section]?.[key] || key;
}
